/**
 * Emits `src/db/schema-sql.ts` — the SQLite DDL for `src/db/schema.ts`, as a
 * string the runtime can execute.
 *
 * Why this exists: the schema normally reaches the database through
 * `drizzle-kit push` (wired into `predev` / `prestart`). Serverless hosts never
 * run those hooks — they invoke their own server entrypoint, not `npm start` —
 * and `drizzle-kit` is a devDependency that is not present in the deployed
 * bundle. So the runtime needs the DDL compiled in.
 *
 * The file is generated, not hand-written, so it cannot drift from the Drizzle
 * schema. `tests/schema-sql.test.ts` fails if it is stale.
 */
import { execFileSync } from "node:child_process";
import { readFileSync, rmSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const outDir = join(root, "drizzle");
const target = join(root, "src", "db", "schema-sql.ts");

// `drizzle-kit generate` refuses `--out` alongside `--config`, so it writes to
// the `out` declared in drizzle.config.ts ("./drizzle") and we remove it after.
rmSync(outDir, { recursive: true, force: true });
try {
  execFileSync("npx", ["drizzle-kit", "generate"], { cwd: root, stdio: ["ignore", "pipe", "pipe"] });

  const journal = JSON.parse(readFileSync(join(outDir, "meta", "_journal.json"), "utf8"));
  const sql = journal.entries
    .map((entry) => readFileSync(join(outDir, `${entry.tag}.sql`), "utf8"))
    .join("\n");

  // Split on drizzle's marker and make every statement idempotent, so the
  // runtime can apply this on every cold start without a guard table.
  const statements = sql
    .split("--> statement-breakpoint")
    .map((statement) => statement.trim())
    .filter(Boolean)
    .map(makeIdempotent);

  if (!statements.length) throw new Error("drizzle-kit produced no SQL — schema.ts may be empty.");

  const unknown = statements.filter((statement) => !/^CREATE (UNIQUE )?(TABLE|INDEX)/i.test(statement));
  if (unknown.length) {
    throw new Error(
      "Refusing to write schema-sql.ts: drizzle-kit emitted statements this " +
        `script cannot make idempotent:\n${unknown.join("\n")}\n` +
        "Update scripts/generate-schema-sql.mjs to handle them.",
    );
  }

  writeFileSync(
    target,
    `// Generated by scripts/generate-schema-sql.mjs from src/db/schema.ts — do not edit.
// Regenerate with \`npm run db:schema-sql\`. Staleness is caught by \`npm test\`.
export const schemaStatements = ${JSON.stringify(statements, null, 2)} as const;
`,
  );

  console.log(`Wrote ${statements.length} DDL statements to src/db/schema-sql.ts`);
} finally {
  rmSync(outDir, { recursive: true, force: true });
}

/** Add IF NOT EXISTS to CREATE TABLE / CREATE INDEX so re-running is a no-op. */
function makeIdempotent(statement) {
  if (/^CREATE TABLE IF NOT EXISTS/i.test(statement)) return statement;
  if (/^CREATE (UNIQUE )?INDEX IF NOT EXISTS/i.test(statement)) return statement;
  if (/^CREATE TABLE\s+/i.test(statement)) return statement.replace(/^CREATE TABLE\s+/i, "CREATE TABLE IF NOT EXISTS ");
  if (/^CREATE (UNIQUE )?INDEX\s+/i.test(statement)) {
    return statement.replace(/^CREATE (UNIQUE )?INDEX\s+/i, "CREATE $1INDEX IF NOT EXISTS ");
  }
  return statement;
}

